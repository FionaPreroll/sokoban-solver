/**
 * Showcase screenshots of the built site (dist/) into dist/screenshots/.
 * Run after `pnpm build`; the Pages workflow deploys them, nothing is committed.
 *
 *   node scripts/screenshots.ts [--out dist/screenshots]
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { chromium, devices, type Browser, type Page } from "@playwright/test";
import { preview } from "vite";

const { values } = parseArgs({ options: { out: { type: "string", default: "dist/screenshots" } } });
const outDir = values.out;
mkdirSync(outDir, { recursive: true });

const server = await preview({ preview: { port: 4175, host: "127.0.0.1", strictPort: true }, logLevel: "warn" });
const base = "http://127.0.0.1:4175/";

async function solveAndStep(page: Page, steps: number): Promise<void> {
  await page.locator("#solve").click();
  await page.locator("#copy-moves:enabled").waitFor({ timeout: 60_000 });
  // Keyboard stepping, so Playwright does not scroll buttons into view.
  for (let i = 0; i < steps; i++) await page.keyboard.press("ArrowRight");
}

async function desktop(browser: Browser, theme: string, file: string): Promise<void> {
  const ctx = await browser.newContext({ viewport: { width: 1280, height: 860 }, deviceScaleFactor: 2 });
  await ctx.addInitScript((t) => {
    localStorage.setItem("sokoban-solver:theme", t);
  }, theme);
  const page = await ctx.newPage();
  await page.goto(base);
  await page.locator("#layer-path").check();
  await solveAndStep(page, 17);
  await page.evaluate(() => {
    window.scrollTo(0, 0);
  });
  await page.mouse.move(0, 0);
  await page.waitForTimeout(1600); // let the result flash fade
  await page.screenshot({ path: join(outDir, file) });
  await ctx.close();
}

const browser = await chromium.launch();
const shots: { file: string; title: string }[] = [];
try {
  for (const [theme, title] of [
    ["classic", "Desktop, Classic theme"],
    ["night", "Desktop, Night theme"],
    ["paper", "Desktop, Paper theme"],
    ["contrast", "Desktop, High contrast theme"],
    ["cga", "Desktop, CGA theme"],
  ] as const) {
    const file = `desktop-${theme}.png`;
    await desktop(browser, theme, file);
    shots.push({ file, title });
  }

  // Mobile: right after solving, the board stays on top and the controls are below it.
  {
    const ctx = await browser.newContext({ ...devices["Pixel 7"] });
    const page = await ctx.newPage();
    await page.goto(base);
    await page.screenshot({ path: join(outDir, "mobile-start.png") });
    shots.push({ file: "mobile-start.png", title: "Mobile, start" });
    await page.locator("#solve").scrollIntoViewIfNeeded();
    await solveAndStep(page, 9);
    await page.locator("#solve").evaluate((el) => {
      (el as HTMLElement).blur();
    });
    await page.waitForTimeout(1600);
    await page.screenshot({ path: join(outDir, "mobile-solved.png") });
    shots.push({ file: "mobile-solved.png", title: "Mobile, after solving" });
    await ctx.close();
  }

  // Mobile in the CGA theme, mid-solution.
  {
    const ctx = await browser.newContext({ ...devices["Pixel 7"] });
    await ctx.addInitScript(() => {
      localStorage.setItem("sokoban-solver:theme", "cga");
    });
    const page = await ctx.newPage();
    await page.goto(base);
    await page.locator("#solve").scrollIntoViewIfNeeded();
    await solveAndStep(page, 20);
    await page.locator("#solve").evaluate((el) => {
      (el as HTMLElement).blur();
    });
    await page.waitForTimeout(1600);
    await page.screenshot({ path: join(outDir, "mobile-cga.png") });
    shots.push({ file: "mobile-cga.png", title: "Mobile, CGA theme" });
    await ctx.close();
  }

  // About dialog.
  {
    const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 2 });
    const page = await ctx.newPage();
    await page.goto(base);
    await page.getByRole("button", { name: "About", exact: true }).click();
    await page.getByRole("dialog").waitFor();
    await page.screenshot({ path: join(outDir, "about.png") });
    shots.push({ file: "about.png", title: "About dialog" });
    await ctx.close();
  }
} finally {
  await browser.close();
  await new Promise<void>((resolve) =>
    server.httpServer.close(() => {
      resolve();
    }),
  );
}

const items = shots.map(
  (s) =>
    `<figure><a href="${s.file}"><img src="${s.file}" alt="${s.title}" loading="lazy"></a><figcaption>${s.title}</figcaption></figure>`,
);
writeFileSync(
  join(outDir, "index.html"),
  `<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>Sokoban Solver screenshots</title>
<style>body{font-family:Georgia,serif;max-width:1100px;margin:auto;padding:16px}figure{margin:0 0 28px}img{max-width:100%;border:1px solid #000}</style>
<h1>Sokoban Solver screenshots</h1><p>Generated by CI from this deployment. <a href="../">Open the app</a>.</p>${items.join("")}`,
);
console.log(`wrote ${String(shots.length)} screenshots to ${outDir}`);
